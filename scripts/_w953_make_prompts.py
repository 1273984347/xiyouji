def main() -> int:
    src = json.load(io.open(SRC, encoding="utf-8"))
    master = src["requests"][0]["prompt"].split("主体：")[0]
    if len(master) < 100:
        print("FATAL 上批母版异常短")
        return 2

    for bi in (1, 2, 3):
        items = SUBJECTS[(bi - 1) * 4: bi * 4]
        reqs = []
        for stem, _topic, subject in items:
            reqs.append({
                "aspect_ratio": "3:4",
                "resolution": "2K",
                "output_file": "plate-line-%s.png" % stem,
                "prompt": master + "主体：" + subject,
            })
        masters = {r["prompt"].split("主体：")[0] for r in reqs}
        if len(masters) != 1 or masters.pop() != master:
            print("FATAL batch%d 母版与 W952 不逐字一致" % bi)
            return 2
        p = os.path.join(OUT, "_w953_batch%d.json" % bi)
        io.open(p, "w", encoding="utf-8").write(
            json.dumps({"requests": reqs}, ensure_ascii=False, indent=2))
        print("写出 %s（%d 条·母版与 W952 逐字相同）" % (os.path.basename(p), len(reqs)))

    print("\n母版全文（%d 字符·一字未改）：\n%s" % (len(master), master))
    return 0


if __name__ == "__main__":
    sys.exit(main())
