#!/usr/bin/env bash
# install_hooks.sh — 幂等安装 agent-guardrails 钩子段（W1077 立·用户令）
#
# 行为：
#   1) 若目标钩子没有标记块：在末尾 `exit 0` 之前插入；无 `exit 0` 则追加并补一个。
#   2) 若已有 `# >>> agent-guardrails block ...` 标记块：原地整段替换（不叠加）。
#   3) 若目标钩子不存在：新建（shebang + 标记块 + exit 0），并置可执行位。
#   4) 内容零差异时不写盘（幂等）。
#
# 用法：
#   bash scripts/install_hooks.sh                 # 装到当前仓库
#   bash scripts/install_hooks.sh <仓库根目录>      # 装到指定仓库（fresh clone 验证用）

set -eu

START='# >>> agent-guardrails block（由 scripts/install_hooks.sh 管理·勿手改）>>>'
END='# <<< agent-guardrails block <<<'

TARGET="${1:-}"
if [ -z "$TARGET" ]; then
  TARGET=$(git rev-parse --show-toplevel 2>/dev/null) || {
    echo "[FAIL] 不在 git 仓库内，请显式传入目标仓库根目录" >&2
    exit 2
  }
fi
[ -d "$TARGET/.git" ] || { echo "[FAIL] 目标不是 git 仓库：$TARGET" >&2; exit 2; }

HOOKS_DIR="$TARGET/.git/hooks"
HOOK="$HOOKS_DIR/pre-commit"
mkdir -p "$HOOKS_DIR"

BLOCK_FILE=$(mktemp)
TMP_FILE=$(mktemp)
trap 'rm -f "$BLOCK_FILE" "$TMP_FILE" "$TMP_FILE.norm"' EXIT

cat > "$BLOCK_FILE" <<'BLOCK_EOF'
# agent-guardrails：只检查暂存区的 .py（W1077 立·用户令）
# 位置保证：gitleaks 与 verify_delivery 已在上面执行完毕，本段只追加、不替换任何既有检查。
# 范围：git diff --cached --diff-filter=ACM；豁免 tmpe/ 与 _ 前缀一次性脚本（与 pyproject 口径一致）。
ROOT="${ROOT:-$(git rev-parse --show-toplevel 2>/dev/null)}"
[ -n "$ROOT" ] || exit 0
STAGED_PY=$(git -C "$ROOT" diff --cached --name-only --diff-filter=ACM -- '*.py' | while IFS= read -r f; do
  [ -n "$f" ] || continue
  case "$f" in tmpe/*) continue ;; esac
  case "${f##*/}" in _*) continue ;; esac
  [ -f "$ROOT/$f" ] && printf '%s\n' "$f"
done)
if [ -n "$STAGED_PY" ]; then
  COUNT=$(printf '%s\n' "$STAGED_PY" | wc -l | tr -d ' ')
  echo ""
  echo "== agent-guardrails：暂存区 .py 结构检查（$COUNT 个；宽档阈值 + api_diff 阻断）=="
  if command -v bash >/dev/null 2>&1; then
    # shellcheck disable=SC2086
    AGENT_GUARDRAILS_STAMP=1 bash "$ROOT/scripts/guardrails/check_changed.sh" --strict-api $STAGED_PY || {
      echo ""
      echo "agent-guardrails 检查未通过，提交被阻止（误报可 git commit --no-verify）。"
      exit 1
    }
  else
    echo "[SKIP] 未找到 bash，agent-guardrails 结构检查跳过（不阻断）。"
  fi
fi
BLOCK_EOF

INSERT=0

# 框架接管告警（W1077）：pre-commit install 会重写本钩子；此处只在检测到框架生成标记时提示。
if [ -f "$HOOK" ] && ! grep -qF "$START" "$HOOK" && grep -qF "generated by pre-commit" "$HOOK"; then
  echo "[WARN] 检测到钩子由 pre-commit 框架生成：安装会把 guardrails 段并入，但下次 pre-commit install 仍会覆盖。" >&2
  echo "       对策：install 后重跑本脚本；或使用 .pre-commit-config.yaml 内的 agent-guardrails 本地 hook（两条路径已做同索引去重）。" >&2
fi

if [ ! -f "$HOOK" ]; then
  {
    printf '#!/bin/sh\n\n'
    printf '%s\n' "$START"
    cat "$BLOCK_FILE"
    printf '%s\n' "$END"
    printf '\nexit 0\n'
  } > "$TMP_FILE"
elif grep -qF "$START" "$HOOK"; then
  awk -v s="$START" -v e="$END" -v bf="$BLOCK_FILE" '
    $0 == s {print; while ((getline line < bf) > 0) print line; skip=1; next}
    skip && $0 == e {print e; skip=0; next}
    skip {next}
    {print}
  ' "$HOOK" > "$TMP_FILE"
  if ! grep -qF "$END" "$TMP_FILE"; then
    echo "[WARN] 起始标记存在但结束标记缺失，改按「无标记插入」处理" >&2
    cp "$HOOK" "$TMP_FILE"
    INSERT=1
  fi
else
  cp "$HOOK" "$TMP_FILE"
  INSERT=1
fi

if [ "$INSERT" -eq 1 ]; then
  LAST=$(awk '/^exit 0$/{n=NR} END{print n+0}' "$HOOK")
  {
    if [ "$LAST" -gt 0 ]; then
      head -n $((LAST - 1)) "$HOOK"
      printf '%s\n' "$START"
      cat "$BLOCK_FILE"
      printf '%s\n' "$END"
      tail -n +"$LAST" "$HOOK"
    else
      cat "$HOOK"
      printf '\n'
      printf '%s\n' "$START"
      cat "$BLOCK_FILE"
      printf '%s\n' "$END"
      printf '\nexit 0\n'
    fi
  } > "$TMP_FILE"
fi

# 统一 LF 行尾（与仓库 .gitattributes 口径一致）：避免原钩子 CRLF 导致二次安装出现 EOL 假差异
tr -d '\r' < "$TMP_FILE" > "$TMP_FILE.norm"
mv "$TMP_FILE.norm" "$TMP_FILE"

if cmp -s "$TMP_FILE" "$HOOK"; then
  chmod +x "$HOOK" 2>/dev/null || true
  echo "[OK] 钩子已是最新（零差异）：$HOOK"
else
  mv "$TMP_FILE" "$HOOK"
  chmod +x "$HOOK"
  echo "[OK] 已安装/更新：$HOOK"
fi
