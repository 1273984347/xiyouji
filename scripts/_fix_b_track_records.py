def apply(path: Path, pairs) -> None:
    t = path.read_text(encoding="utf-8")
    for old, new in pairs:
        assert t.count(old) == 1, "not unique/found in %s: %s" % (path.name, old[:60])
        t = t.replace(old, new)
    path.write_text(t, encoding="utf-8")
    print("ok:", path.name)


