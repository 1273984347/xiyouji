def apply_pairs(t, pairs, label):
    for old, new in pairs:
        # 文稿引号约定为直引号（U+0022）——脚本内以弯引号书写的中西文引述统一归一
        old = old.replace("\u201c", '"').replace("\u201d", '"')
        new = new.replace("\u201c", '"').replace("\u201d", '"')
        c = t.count(old)
        if c == 1:
            t = t.replace(old, new)
        elif c == 0 and t.count(new) >= 1:
            continue  # 幂等
        else:
            raise AssertionError(f"{label}: 「{old[:36]}…」出现 {c} 次")
    return t


