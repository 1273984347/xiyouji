def main():
    for path in FILES:
        with open(path, encoding="utf-8") as f:
            text = f.read()
        for old, new, expect in EDITS:
            n = text.count(old)
            assert n == expect, "%s: 命中 %d 次（期望 %d）：%s" % (
                path.rsplit("\\", 1)[-1], n, expect, old[:40])
            text = text.replace(old, new)
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        print("OK", path.rsplit("\\", 1)[-1], len(EDITS), "edits")
    return 0


