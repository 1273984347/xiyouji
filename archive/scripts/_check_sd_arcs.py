def read(p): return open(p, encoding="utf-8").read()
def parse_declared(body):
    m = re.search(r"推测对应原著回号:\s*第(\d+)(?:-(\d+))?回", body)
    if not m: return None
    a=int(m.group(1)); b=int(m.group(2)) if m.group(2) else a
    return list(range(a,b+1))
def extract_body(text):
    text = re.sub(r"<!--.*?-->","",text,flags=re.DOTALL)
    text = re.sub(r"^#\s.*$","",text,count=1,flags=re.MULTILINE)
    return text
def arc_tally(text):
    c = Counter()
    for term, chs in TERMS:
        if term in text:
            for ch in set(chs):
                c[CH2ARC[ch]] += 1
    return c


def main():
    files = sorted(glob.glob(os.path.join(SHENDU,"SD*.md")))
    true_corrupt, comparative, drift_only = [], [], []
    for p in files:
        num = int(re.match(r"SD(\d+)\.md", os.path.basename(p)).group(1))
        txt = read(p)
        declared = parse_declared(txt)
        first = txt.splitlines()[0] if txt.splitlines() else ""
        title = first.split("·",1)[1].strip() if "·" in first else first
        body = extract_body(txt)
        t_arc = arc_tally(title)
        b_arc = arc_tally(body)
        t_top = t_arc.most_common(1)[0][0] if t_arc else None
        b_top = b_arc.most_common(1)[0][0] if b_arc else None
        if t_top is None or b_top is None:
            continue
        t_count = b_arc.get(t_top, 0)          # 正文中属于“标题主题 arc”的锚点数
        b_top_count = b_arc.get(b_top, 0)
        # 是否声明回号落在标题 arc
        dec_in_title_arc = declared is not None and any(CH2ARC[c]==t_top for c in declared)
        if t_top == b_top:
            # 标题与正文同 arc：仅可能是注释漂移
            if not dec_in_title_arc:
                drift_only.append((num, declared, t_top, title))
            continue
        # 标题 arc != 正文主导 arc
        if t_count == 0 and b_top_count >= 3:
            true_corrupt.append((num, declared, t_top, b_top, t_count, b_top_count, title, b_arc.most_common(3)))
        else:
            comparative.append((num, declared, t_top, b_top, t_count, b_top_count, title, b_arc.most_common(3)))

    print(f"=== 真 corruption（标题arc在正文锚点=0，被异arc主导）: {len(true_corrupt)} ===")
    for num,dec,ta,ba,tc,bc,title,top in true_corrupt:
        print(f"SD{num:03d} 声明{dec} 标题arc={ta} 正文主导arc={ba}(×{bc}) 标题arc锚点={tc} | '{title}'")
        print(f"    正文arc命中: {top}")
    print(f"\n=== 跨章比较型（合法，标题arc在正文中仍有锚点）: {len(comparative)} ===")
    for num,dec,ta,ba,tc,bc,title,top in comparative:
        print(f"SD{num:03d} 声明{dec} 标题arc={ta}(正文×{tc}) 主导arc={ba}(×{bc}) | '{title}'")
    print(f"\n=== 仅注释漂移（标题=正文同arc，声明回号不在该arc）: {len(drift_only)} ===")
    for num,dec,ta,title in drift_only:
        print(f"SD{num:03d} 声明{dec} 实际arc={ta} | '{title}'")


if __name__ == "__main__":
    main()
