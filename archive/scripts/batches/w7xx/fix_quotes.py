def grab(num, start_kw, end_kw, include_end=True):
    """从第 num 回提取 [start_kw, end_kw] 闭区间精确文本（end_kw 须在 start_kw 之后）。"""
    t = CH[num]
    i = t.find(start_kw)
    assert i >= 0, f'ch{num} 起点未找到: {start_kw!r}'
    j = t.find(end_kw, i)
    assert j >= 0, f'ch{num} 终点未找到: {end_kw!r}'
    seg = t[i:j + (len(end_kw) if include_end else 0)]
    return seg


