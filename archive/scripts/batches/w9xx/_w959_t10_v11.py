def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    with open(DOC, "rb") as f:
        raw = f.read()
    before_len = len(raw)
    nl = b"\r\n" if b"\r\n" in raw else b"\n"
    lines = raw.split(nl)
    if lines and lines[-1] == b"":
        lines = lines[:-1]

    applied = 0
    # 倒序应用（行号不因前面的改动而位移）
    for lineno, assert_tok, old, new in sorted(JOBS, key=lambda j: -j[0]):
        if lineno < 1 or lineno > len(lines):
            print("ABORT  行号越界：%d（文件共 %d 行）" % (lineno, len(lines)))
            return 1
        line = lines[lineno - 1].decode("utf-8")
        if assert_tok not in line:
            print("ABORT  第 %d 行不含断言片段「%s」⇒ 文件已漂移：%s" % (lineno, assert_tok, line[:90]))
            return 1
        if old is not None:
            c = line.count(old)
            if c != 1:
                print("ABORT  第 %d 行内片段命中 %d ≠ 期望 1：%s" % (lineno, c, old[:60]))
                return 1
            newline = line.replace(old, new, 1)
        else:
            newline = new
        lines[lineno - 1] = newline.encode("utf-8")
        applied += 1

    out = nl.join(lines)
    # 保持文件末尾换行
    if not out.endswith(nl):
        out += nl

    print("作业 %d 条 · 字节 %d → %d" % (applied, before_len, len(out)))
    if args.dry_run:
        for lineno, assert_tok, old, new in sorted(JOBS, key=lambda j: j[0]):
            print("  L%-4d %s" % (lineno, assert_tok[:40]))
        print("DRY-RUN：未写盘")
        return 0

    with open(DOC, "wb") as f:
        f.write(out)
    print("OK  T10 报告已订正（V1.1 计数口径）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
