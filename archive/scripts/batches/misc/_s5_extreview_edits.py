FAILS = []
def apply(fn, pairs):
    p = os.path.join(ROOT, fn)
    with open(p, encoding='utf-8', newline='') as f:
        t = f.read()
    for tag, old, new, cnt in pairs:
        n = t.count(old)
        if n != cnt:
            FAILS.append(f'{fn} [{tag}] expect {cnt} hit, got {n}')
            continue
        t = t.replace(old, new)
    with open(p, 'w', encoding='utf-8', newline='') as f:
        f.write(t)
    print(f'OK {fn} ({len(pairs)} pairs)')

